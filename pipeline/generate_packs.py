#!/usr/bin/env python3
"""Generate packs/en/*.json from src/word/pack.ts + deterministic cross-checks.

Cross-check = offline stand-in for open-weights verification (Muse Glimmer NOT
downloaded — needs explicit user OK, ~17 GB). Flags disagreements to
pipeline/review.md; never auto-fixes stored data.
Usage: python pipeline/generate_packs.py
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACK_TS = ROOT / "src/word/pack.ts"
OUT = ROOT / "packs/en"
REVIEW = ROOT / "pipeline/review.md"

SETS = {"ROOM_WORDS": "living-room", "KITCHEN_PROPS": "kitchen",
        "VERBS": "grammar-verbs", "PHRASAL_VERBS": "grammar-phrasal-verbs",
        "PREPOSITIONS": "grammar-prepositions", "ADJECTIVES": "grammar-adjectives"}
IRREGULAR_PLURALS = {"shelf": "shelves"}
VOWEL_SOUND_AN = {"apple", "hour", "honest"}  # stored-article ground truth exceptions

def parse_entries():
    text = PACK_TS.read_text(encoding="utf-8")
    sets = {}
    for name, slug in SETS.items():
        block = re.search(rf"export const {name}[^=]*=\s*\[(.*?)\n\];", text, re.S).group(1)
        entries = []
        for line in block.splitlines():
            line = line.strip()
            if not line.startswith("{"):
                continue
            e = {}
            for key in ("id", "word", "ipa", "partOfSpeech", "plural", "article", "cefr",
                        "example", "sceneLabel", "propId", "wakeFx", "rarity", "audio"):
                m = re.search(rf"\b{key}: '([^']*)'", line)
                if m:
                    e[key] = m.group(1)
            h = re.search(r"helper: \{ es: '([^']*)', vi: '([^']*)' \}", line)
            e["helper"] = {"es": h.group(1), "vi": h.group(2)}
            entries.append(e)
        sets[slug] = entries
    return sets

def expected_article(word):
    return "an" if word in VOWEL_SOUND_AN or word[0].lower() in "aeiou" else "a"

def expected_plural(word):
    if word in IRREGULAR_PLURALS:
        return IRREGULAR_PLURALS[word]
    if re.search(r"(s|x|z|ch|sh)$", word):
        return word + "es"
    if re.search(r"[^aeiou]y$", word):
        return word[:-1] + "ies"
    return word + "s"

def crosscheck(sets):
    problems = []
    for slug, entries in sets.items():
        seen = set()
        for e in entries:
            tag = f"{slug}/{e.get('id','?')}"
            if e["id"] in seen:
                problems.append(f"- `{tag}`: duplicate id")
            seen.add(e["id"])
            if not (e["ipa"].startswith("/") and e["ipa"].endswith("/")):
                problems.append(f"- `{tag}`: IPA missing /slashes/: `{e['ipa']}`")
            if e["cefr"] not in ("A1", "A2"):
                problems.append(f"- `{tag}`: CEFR not A1/A2: `{e['cefr']}`")
            if e["partOfSpeech"] == "noun":
                if e.get("article") != expected_article(e["word"]):
                    problems.append(f"- `{tag}`: article stored `{e.get('article')}` != rule `{expected_article(e['word'])}` — HUMAN CHECK (sound, not spelling)")
                if e.get("plural") != expected_plural(e["word"]):
                    problems.append(f"- `{tag}`: plural stored `{e.get('plural')}` != rule `{expected_plural(e['word'])}`")
            if e["word"].lower() not in e["example"].lower() and e.get("plural", "###") not in e["example"]:
                problems.append(f"- `{tag}`: example does not contain word: \"{e['example']}\"")
            for lang in ("es", "vi"):
                if not e["helper"].get(lang):
                    problems.append(f"- `{tag}`: helper.{lang} empty")
            if bool(e.get("sceneLabel")) == bool(e.get("propId")):
                problems.append(f"- `{tag}`: need exactly one of sceneLabel/propId (grammar words exempt if in grammar-*)" if not slug.startswith("grammar") else f"- `{tag}`: grammar word must have neither sceneLabel nor propId" if (e.get("sceneLabel") or e.get("propId")) else "")
            problems = [p for p in problems if p]
    return problems

def main():
    sets = parse_entries()
    OUT.mkdir(parents=True, exist_ok=True)
    total = 0
    for slug, entries in sets.items():
        room = "living-room" if slug == "living-room" else slug
        pack = {"packId": f"en-{slug}", "lang": "en", "room": room, "version": 1, "words": entries}
        (OUT / f"{slug}.json").write_text(json.dumps(pack, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        total += len(entries)
        print(f"packs/en/{slug}.json: {len(entries)} words")
    problems = crosscheck(sets)
    REVIEW.write_text(
        "# Pipeline review — disagreements for human review\n\n"
        "Generated by `pipeline/generate_packs.py` (deterministic cross-check; Muse Glimmer not downloaded — pending user OK).\n"
        "Stored pack data is never auto-fixed. Resolve each item in `src/word/pack.ts`, re-run.\n\n"
        + ("\n".join(problems) if problems else "No disagreements found.") + "\n", encoding="utf-8")
    print(f"total {total} words; {len(problems)} disagreement(s) -> pipeline/review.md")
    return 0

if __name__ == "__main__":
    sys.exit(main())
