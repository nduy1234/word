#!/usr/bin/env node
/** Node runner for pipeline (same outputs as generate_packs.py + dry-run manifests).
 * generate_packs.py stays canonical for key-enabled art/audio; this runs anywhere Node runs. */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const text = readFileSync(join(ROOT, 'src/word/pack.ts'), 'utf8');
const SETS = { ROOM_WORDS: 'living-room', KITCHEN_PROPS: 'kitchen', VERBS: 'grammar-verbs',
  PHRASAL_VERBS: 'grammar-phrasal-verbs', PREPOSITIONS: 'grammar-prepositions', ADJECTIVES: 'grammar-adjectives' };
const IRREG = { shelf: 'shelves' };
const expArticle = (w) => (w === 'apple' || 'aeiou'.includes(w[0].toLowerCase()) ? 'an' : 'a');
const expPlural = (w) => IRREG[w] ?? (/(s|x|z|ch|sh)$/.test(w) ? w + 'es' : /[^aeiou]y$/.test(w) ? w.slice(0, -1) + 'ies' : w + 's');

const sets = {};
for (const [name, slug] of Object.entries(SETS)) {
  const block = text.match(new RegExp(`export const ${name}[^=]*=\\s*\\[([\\s\\S]*?)\\n\\];`))[1];
  sets[slug] = block.split('\n').filter((l) => l.trim().startsWith('{')).map((line) => {
    const e = {};
    for (const k of ['id','word','ipa','partOfSpeech','plural','article','cefr','example','sceneLabel','propId','wakeFx','rarity','audio']) {
      const m = line.match(new RegExp(`\\b${k}: '([^']*)'`)); if (m) e[k] = m[1];
    }
    const h = line.match(/helper: \{ es: '([^']*)', vi: '([^']*)' \}/);
    e.helper = { es: h[1], vi: h[2] };
    return e;
  });
}

mkdirSync(join(ROOT, 'packs/en'), { recursive: true });
mkdirSync(join(ROOT, 'public/assets'), { recursive: true });
const problems = [];
let total = 0;
const all = [];
for (const [slug, words] of Object.entries(sets)) {
  writeFileSync(join(ROOT, `packs/en/${slug}.json`),
    JSON.stringify({ packId: `en-${slug}`, lang: 'en', room: slug, version: 1, words }, null, 2) + '\n');
  total += words.length; all.push(...words);
  const seen = new Set();
  for (const e of words) {
    const t = `${slug}/${e.id}`;
    if (seen.has(e.id)) problems.push(`- \`${t}\`: duplicate id`);
    seen.add(e.id);
    if (!e.ipa.startsWith('/') || !e.ipa.endsWith('/')) problems.push(`- \`${t}\`: IPA missing slashes`);
    if (!['A1','A2'].includes(e.cefr)) problems.push(`- \`${t}\`: CEFR not A1/A2`);
    if (e.partOfSpeech === 'noun') {
      if (e.article !== expArticle(e.word)) problems.push(`- \`${t}\`: article ${e.article} != rule ${expArticle(e.word)} — HUMAN CHECK`);
      if (e.plural !== expPlural(e.word)) problems.push(`- \`${t}\`: plural ${e.plural} != rule ${expPlural(e.word)}`);
    }
    if (!e.example.toLowerCase().includes(e.word.toLowerCase())) problems.push(`- \`${t}\`: example missing word`);
    if (!e.helper.es || !e.helper.vi) problems.push(`- \`${t}\`: helper empty`);
  }
}
writeFileSync(join(ROOT, 'pipeline/review.md'),
  '# Pipeline review — disagreements for human review\n\nGenerated by pipeline/generate_packs (deterministic cross-check; Muse Glimmer not downloaded — pending user OK). Stored data never auto-fixed.\n\n'
  + (problems.length ? problems.join('\n') : 'No disagreements found.') + '\n');

const nouns = all.filter((w) => w.partOfSpeech === 'noun');
const STYLE = 'soft stylized low-poly sticker, rounded chunky silhouette, warm off-white background #FFF4E0, ink outline #2D2438, no text, no brands, no people';
writeFileSync(join(ROOT, 'public/assets/art-manifest.json'), JSON.stringify(
  nouns.map((w) => ({ id: w.id, file: `art/${w.id}.png`, model: 'muse-image-1.0', prompt: `${STYLE}. Object: ${w.word}.`, status: 'planned-dry-run' })), null, 2) + '\n');
writeFileSync(join(ROOT, 'public/assets/atlas-layout.json'), JSON.stringify(
  { cellPx: 256, cols: 8, ktx2: 'atlas.ktx2', entries: nouns.map((w, i) => ({ id: w.id, file: `art/${w.id}.png`, cell: i })) }, null, 2) + '\n');
writeFileSync(join(ROOT, 'public/assets/audio-manifest.json'), JSON.stringify(
  all.map((w) => ({ id: w.id, locale: 'en-US', text: w.word, file: `audio/en-US/${w.id}.wav`, engine: 'none', status: 'planned-no-engine' })), null, 2) + '\n');
console.log(`packs: ${total} words, ${problems.length} disagreement(s); manifests written (dry-run)`);
